const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const sandbox={window:{},console};vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('ml-game/js/jscratch-project.js','utf8'),sandbox);
const html=fs.readFileSync('ml-game/apps/jscratch.html','utf8');
const definitions=html.slice(html.indexOf('const BLOCKS='),html.indexOf('const EVENT_GAP='));
vm.runInContext(definitions+';window.defs=new Map(Object.values(BLOCKS).flat().map(d=>[d[0],d]));window.zero=ZERO_FIELD_BLOCKS;',sandbox);
const {JScratchProject:project,defs,zero}=sandbox.window;
const block=(type,values=[],stacks={})=>({type,slots:values.map(value=>({type:typeof value==='number'?'number':'text',value:String(value)})),stacks});
const scripts=[{name:'Nested example',blocks:[block('ifBlock',['false'],{main:[block('makeVar',['answer',1])],else:[block('makeVar',['answer',2])]})]}];
assert.equal(project.validate({format:'jscratch',version:1,scripts},defs),3);
const output=project.generate(scripts,defs,zero);new vm.Script(output.code);
assert.match(output.code, /"else"/);assert.match(output.code,/makeVar\("answer", 2\)/);
const large=[{name:'10k project',blocks:Array.from({length:10000},()=>block('changeVarBy',['count',1]))}];
assert.equal(project.validate({format:'jscratch',version:1,scripts:large},defs),10000);
const generated=project.generate(large,defs,zero,{debug:true});new vm.Script(generated.code);assert.equal(generated.locations.size,10000);assert.equal((generated.code.match(/changeVarBy/g)||[]).length,10000);
assert.throws(()=>project.validate({format:'jscratch',version:1,scripts:[{name:'Bad',blocks:[block('unknown')]}]},defs),/Unknown/);
assert.equal(project.format('hello "world"\n','text'),'"hello \\"world\\"\\n"');
const inline=html.slice(html.indexOf('<script>')+8,html.lastIndexOf('</script>'));new vm.Script(inline);
console.log('Passed: all editor syntax, nested else generation, project validation, 10,000-block compilation and debug mapping.');
